SELECT
     CASE WHEN GROUPING(X.MARCA) = 1 THEN 1 ELSE 0 END AS eh_total
    ,X.MARCA
    -- Ruptura D-1 (HUB RIO): valores únicos, lidos da linha TOTAL
    ,(SELECT ISNULL(SUM(QTDE_ALTERADA),0) FROM #RUP)  AS rup_pecas
    ,(SELECT ISNULL(SUM(QTDE_PECAS),0)    FROM #PICK) AS pick_pecas
    -- Integrado: vendas em D-1
    ,COUNT(DISTINCT CASE WHEN X.DT_VENDA = @D1 THEN X.CHAVE_2 END)             AS ped_integrado
    ,SUM(CASE WHEN X.DT_VENDA = @D1 THEN ISNULL(X.QTDE_TOTAL,0)  ELSE 0 END)  AS pc_integrado
    ,SUM(CASE WHEN X.DT_VENDA = @D1 THEN ISNULL(X.VALOR_TOTAL,0) ELSE 0 END)  AS rs_integrado
    -- Atendido: expedidos em D-1
    ,COUNT(DISTINCT CASE WHEN X.DT_EXPEDIDO = @D1 THEN X.CHAVE_2 END)            AS ped_atendido
    ,SUM(CASE WHEN X.DT_EXPEDIDO = @D1 THEN ISNULL(X.QTDE_TOTAL,0)  ELSE 0 END) AS pc_atendido
    ,SUM(CASE WHEN X.DT_EXPEDIDO = @D1 THEN ISNULL(X.VALOR_TOTAL,0) ELSE 0 END) AS rs_atendido
    -- Backlog pendente: vendidos em D-1 que continuam sem expedição NO MOMENTO DA ATUALIZAÇÃO
    ,COUNT(DISTINCT CASE WHEN X.DT_VENDA = @D1 AND X.ABERTO = 1 THEN X.CHAVE_2 END)             AS ped_pendente
    ,SUM(CASE WHEN X.DT_VENDA = @D1 AND X.ABERTO = 1 THEN ISNULL(X.QTDE_TOTAL,0)  ELSE 0 END)  AS pc_pendente
    ,SUM(CASE WHEN X.DT_VENDA = @D1 AND X.ABERTO = 1 THEN ISNULL(X.VALOR_TOTAL,0) ELSE 0 END)  AS rs_pendente
    -- Backlog D-7: vendidos de D-7 a D-1 que continuam sem expedição NO MOMENTO DA ATUALIZAÇÃO
    ,COUNT(DISTINCT CASE WHEN X.DT_VENDA BETWEEN @D7 AND @D1 AND X.ABERTO = 1 THEN X.CHAVE_2 END)             AS ped_backlog_7d
    ,SUM(CASE WHEN X.DT_VENDA BETWEEN @D7 AND @D1 AND X.ABERTO = 1 THEN ISNULL(X.QTDE_TOTAL,0)  ELSE 0 END)  AS pc_backlog_7d
    ,SUM(CASE WHEN X.DT_VENDA BETWEEN @D7 AND @D1 AND X.ABERTO = 1 THEN ISNULL(X.VALOR_TOTAL,0) ELSE 0 END)  AS rs_backlog_7d
    -- SLA: pedidos vendidos em D-1. Cumprido = expedido em até a meta de lead time.
    --      Base = cumpridos + descumpridos (expedidos fora da meta + pendentes já acima da meta). Pendentes ainda dentro da meta ficam fora da base.
    ,COUNT(DISTINCT CASE WHEN X.DT_VENDA = @D1 AND X.ABERTO = 0 AND X.LT_MIN <= @META_LT_MIN THEN X.CHAVE_2 END)  AS sla_cumprido
    ,COUNT(DISTINCT CASE WHEN X.DT_VENDA = @D1 AND (X.ABERTO = 0 OR X.LT_MIN > @META_LT_MIN) THEN X.CHAVE_2 END)   AS sla_base
    -- Lead time (venda -> expedição) dos expedidos em D-1 (base: linhas pedido x marca)
    ,SUM(CASE WHEN X.DT_EXPEDIDO = @D1 THEN 1 ELSE 0 END)                                                                  AS qtd_expedidos
    ,SUM(CASE WHEN X.DT_EXPEDIDO = @D1 THEN DATEDIFF(MINUTE, X.DATA_VENDA, X.DATA_EXPEDIDO) / 60.0 ELSE 0 END)            AS soma_lead_time_h
FROM (
    SELECT
         CASE
            WHEN A.MARCA_ORIGINAL LIKE '%FOXTON%'  THEN 'FOXTON'
            WHEN A.MARCA_ORIGINAL LIKE '%FABULA%'  THEN 'FABULA'
            WHEN A.MARCA_ORIGINAL LIKE '%ANIMALE%' THEN 'ANIMALE'
            ELSE A.MARCA_ORIGINAL
         END AS MARCA
        ,CONCAT(A.CODIGO_FILIAL_ORIGEM, A.PEDIDO) AS CHAVE_2
        ,A.QTDE_TOTAL
        ,A.VALOR_TOTAL
        ,A.DATA_VENDA
        ,A.DATA_EXPEDIDO
        ,CAST(A.DATA_VENDA    AS DATE) AS DT_VENDA
        ,CAST(A.DATA_EXPEDIDO AS DATE) AS DT_EXPEDIDO
        ,CASE WHEN A.DATA_EXPEDIDO IS NULL THEN 1 ELSE 0 END AS ABERTO                                  -- sem expedição agora
        ,DATEDIFF(MINUTE, A.DATA_VENDA, ISNULL(A.DATA_EXPEDIDO, @AGORA)) AS LT_MIN                       -- minutos da venda até a expedição (ou até agora, se pendente)
    FROM #DW A
) X
GROUP BY GROUPING SETS ((X.MARCA), ())
ORDER BY GROUPING(X.MARCA), X.MARCA;
