/* =========================================================
   query_ecommerce
   ========================================================= */
SET NOCOUNT ON
SET XACT_ABORT ON

DECLARE @DATAINICIO DATE = '2026-01-01'

DROP TABLE IF EXISTS #DW
DROP TABLE IF EXISTS #GL

/* =========================================================
   PASSO 1: pedidos da tabela gerada (DATA_HORA_INTEGRACAO = data da venda)
   ========================================================= */
SELECT
     D.CODIGO_FILIAL_ORIGEM
    ,D.PEDIDO
    ,CASE
        WHEN D.SITE = 'NV - HUB ES' THEN 'HUB SP'
        WHEN D.CODIGO_FILIAL_ORIGEM IN ('805209','550325','560030','805210','550070','190537') THEN 'HUB RIO'
        ELSE D.SITE
     END AS SITE
    ,LTRIM(RTRIM(D.MARCA)) AS MARCA_ORIGINAL
    ,D.QTDE_TOTAL
    ,D.VALOR_TOTAL
    ,D.VOLUMES
    ,D.DATA_HORA_INTEGRACAO AS DATA_VENDA
    ,D.DATA_EMBALADO
    ,D.DATA_FATURAMENTO
    ,COALESCE(D.DATA_EMBARQUE, D.DATA_EXPEDIDO_WMS, D.EMISSAO_CTE) AS DATA_EXPEDIDO
    ,D.UF_DESTINO_CTE
    ,D.STATUS_PEDIDO
    ,LTRIM(RTRIM(D.TRANSPORTADORA)) AS TRANSPORTADORA
    ,D.NF_NUMERO
    ,D.SERIE_NF
    ,D.PEDIDO_SITE
    ,D.DATA_EM_SEPARACAO
    ,ROW_NUMBER() OVER (PARTITION BY D.CODIGO_FILIAL_ORIGEM, D.PEDIDO, D.MARCA
                        ORDER BY D.DATA_HORA_ATUALIZACAO DESC, D.DATA_FATURAMENTO DESC) AS RN
INTO #DW
FROM DB_VIEWS.dbo.DW_LOGISTICA_PRODUCAO_ECOMMERCE D
WHERE D.DATA_HORA_INTEGRACAO >= @DATAINICIO
  AND D.SITE IN ('HUB RIO','HUB SP','HUB ES','NV - HUB ES','HUB CAROL BASSI','HUB CBA')
  AND D.STATUS_PEDIDO IN ('VALIDO','VÁLIDO')

DELETE #DW WHERE RN > 1

CREATE CLUSTERED INDEX IX_DW ON #DW (CODIGO_FILIAL_ORIGEM, PEDIDO)

/* =========================================================
   PASSO 2: colunas que so existem no gl_EcommerceSoma
   ========================================================= */
SELECT
     G.CODIGO_FILIAL_ORIGEM COLLATE SQL_Latin1_General_CP1_CI_AS AS CODIGO_FILIAL_ORIGEM
    ,G.PEDIDO               COLLATE SQL_Latin1_General_CP1_CI_AS AS PEDIDO
    ,MAX(G.UF_DESTINO)                 AS UF_DESTINO
    ,MAX(G.AGING_ECOMMERCE_EMBALADO)    AS AGING_ECOMMERCE_EMBALADO
    ,MAX(G.AGING_ECOMMERCE_FATURAMENTO) AS AGING_ECOMMERCE_FATURAMENTO
    ,MAX(G.AGING_ECOMMERCE_EXPEDICAO)   AS AGING_ECOMMERCE_EXPEDICAO
    ,MAX(G.DATA_REGISTRO)               AS DATA_REGISTRO
INTO #GL
FROM DbLogistica.dbo.gl_EcommerceSoma G
WHERE G.DATA_VENDA >= @DATAINICIO
  AND EXISTS (SELECT 1 FROM #DW D
              WHERE D.PEDIDO = G.PEDIDO COLLATE SQL_Latin1_General_CP1_CI_AS
                AND D.CODIGO_FILIAL_ORIGEM = G.CODIGO_FILIAL_ORIGEM COLLATE SQL_Latin1_General_CP1_CI_AS)
GROUP BY G.CODIGO_FILIAL_ORIGEM, G.PEDIDO

CREATE CLUSTERED INDEX IX_GL ON #GL (CODIGO_FILIAL_ORIGEM, PEDIDO)

/* =========================================================
   SELECT FINAL (mesmas colunas da v2)
   ========================================================= */
SELECT
     A.RN AS ROW
    ,A.CODIGO_FILIAL_ORIGEM
    ,A.SITE
    ,CONCAT(
        CASE
            WHEN A.MARCA_ORIGINAL LIKE '%FARM%'   THEN 'FARM'
            WHEN A.MARCA_ORIGINAL LIKE '%FOXTON%' THEN 'FOXTON'
            WHEN A.MARCA_ORIGINAL LIKE '%FABULA%' THEN 'FABULA'
            ELSE A.MARCA_ORIGINAL
        END,
        LTRIM(RTRIM(A.PEDIDO))) AS CHAVE
    ,CONCAT(A.CODIGO_FILIAL_ORIGEM, A.PEDIDO) AS CHAVE_2
    ,CASE
        WHEN A.MARCA_ORIGINAL LIKE '%FOXTON%'  THEN 'FOXTON'
        WHEN A.MARCA_ORIGINAL LIKE '%FABULA%'  THEN 'FABULA'
        WHEN A.MARCA_ORIGINAL LIKE '%ANIMALE%' THEN 'ANIMALE'
        ELSE A.MARCA_ORIGINAL
     END AS MARCA
    ,A.PEDIDO
    ,A.QTDE_TOTAL  AS QTDE_PECAS
    ,A.VALOR_TOTAL
    ,A.VOLUMES
    ,DATEPART(HOUR, A.DATA_FATURAMENTO) AS HORA_FATURAMENTO
    ,DATEPART(HOUR, A.DATA_EXPEDIDO)    AS HORA_EXPEDIDO
    ,DATEPART(HOUR, A.DATA_VENDA)       AS HORA_VENDA
    ,CAST(A.DATA_VENDA       AS DATE) AS DT_VENDA
    ,CAST(A.DATA_EMBALADO    AS DATE) AS DT_EMBALADO
    ,CAST(A.DATA_FATURAMENTO AS DATE) AS DT_FATURAMENTO
    ,CAST(A.DATA_EXPEDIDO    AS DATE) AS DT_EXPEDIDO
    ,A.DATA_VENDA
    ,A.DATA_EMBALADO
    ,A.DATA_FATURAMENTO
    ,A.DATA_EXPEDIDO
    ,CASE WHEN A.DATA_EMBALADO IS NULL THEN 'EM ABERTO' ELSE 'EMBALADO' END AS AUX_EMBALADO
    ,CASE
        WHEN A.DATA_FATURAMENTO IS NOT NULL THEN 'FATURADO'
        WHEN A.DATA_EMBALADO    IS NOT NULL THEN 'SEM FATURAMENTO'
        ELSE 'EM ABERTO'
     END AS AUX_FATURAMENTO
    ,CASE
        WHEN A.DATA_EXPEDIDO    IS NOT NULL THEN 'EXPEDIDO'
        WHEN A.DATA_FATURAMENTO IS NOT NULL THEN 'SEM EXPEDIÇÃO'
        WHEN A.DATA_EMBALADO    IS NOT NULL THEN 'SEM FATURAMENTO'
        ELSE 'EM ABERTO'
     END AS AUX_EXPEDICAO
    ,ISNULL(G.UF_DESTINO, A.UF_DESTINO_CTE) AS UF_DESTINO
    ,G.AGING_ECOMMERCE_EMBALADO
    ,G.AGING_ECOMMERCE_FATURAMENTO
    ,G.AGING_ECOMMERCE_EXPEDICAO
    ,A.STATUS_PEDIDO
    ,CASE
        WHEN A.TRANSPORTADORA LIKE '%TOTAL%' THEN 'TOTAL EXPRESSO'
        WHEN A.TRANSPORTADORA LIKE '%LOGGI%' THEN 'LOGGI'
        WHEN A.TRANSPORTADORA LIKE '%JOY2W%' THEN 'JOY2W'
        WHEN A.TRANSPORTADORA LIKE '%GFL%'   THEN 'GFL'
        ELSE A.TRANSPORTADORA
     END AS TRANSPORTADORA
    ,A.NF_NUMERO
    ,A.SERIE_NF
    ,G.DATA_REGISTRO
    ,A.PEDIDO_SITE
    ,CASE
        WHEN C.LOTE IS NULL THEN 'SEM LOTE'
        WHEN A.QTDE_TOTAL > 1 THEN 'MULTISKU'
        WHEN A.QTDE_TOTAL = 1 THEN 'MONOSKU'
        ELSE 'ERRO'
     END AS TIPO_LOTE
    ,C.ID_USUARIO_LOTE
    ,RTRIM(LTRIM(U.NOME_COMPLETO)) AS NOME_COMPLETO
    ,CASE
        WHEN A.DATA_EMBALADO    IS NULL THEN 'PICKING PENDENTE'
        WHEN A.DATA_FATURAMENTO IS NULL THEN 'FATURAMENTO PENDENTE'
        WHEN A.DATA_EXPEDIDO    IS NULL THEN 'EXPEDICAO PENDENTE'
        ELSE 'ERRO'
     END AS STATUS
    ,C.ID_PARAMETRIZACAO_ONDA AS ID_ONDA
    ,RTRIM(LTRIM(E.DESCRICAO)) AS DESCRICAO_ONDA
    ,C.LOTE
    ,C.INATIVO
    ,ISNULL(CAST(A.DATA_EM_SEPARACAO AS DATE), A.DATA_EMBALADO) AS DATA_PICKING
FROM #DW A
LEFT JOIN #GL G
    ON G.CODIGO_FILIAL_ORIGEM = A.CODIGO_FILIAL_ORIGEM
   AND G.PEDIDO = A.PEDIDO
LEFT JOIN SOMA.dbo.SS_WMS_LOTE_PEDIDOS_ECOMMERCE C
    ON C.CODIGO_FILIAL_ORIGEM = A.CODIGO_FILIAL_ORIGEM
   AND C.PEDIDO = A.PEDIDO   -- PEDIDO e numerico no WMS (igual a v2)
LEFT JOIN SOMA.dbo.SS_USUARIOS_COLETOR U
    ON U.ID_USUARIO = C.ID_USUARIO_LOTE
LEFT JOIN SOMA.dbo.SS_WMS_PARAMETRIZACAO_LOTES_ECOMMERCE E
    ON E.ID_PARAMETRIZACAO = C.ID_PARAMETRIZACAO_ONDA
